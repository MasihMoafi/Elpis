const assert=require('node:assert/strict');
const path=require('node:path');
const {call,message}=require('./runtime-eval');
module.exports=async({vscode,document,frame,page,provider,eventually,evidence,data})=>{
  const before=provider.requests.length;
  await frame.locator('#ledger-open').click();
  await eventually(async()=>!(await frame.evaluate('d.getElementById("smart-pruning-toggle").disabled')),'runtime Smart Pruning snapshot');
  await frame.pointerClick('#prompt');await frame.locator('#prompt').fill('/prune');await page.keyboard.press('Enter');
  await eventually(async()=>(await frame.locator('#smart-pruning-state').textContent())==='Smart Pruning: on','/prune enables admission-time Smart Pruning');
  assert.equal(provider.requests.length,before,'enabling must not rewrite or prune existing history');
  const original=document.getText(),fact='LEDGER_UNSAVED_FACT_431: delivery closes at 17:45';
  const editor=await vscode.window.showTextDocument(document);
  await editor.edit(edit=>edit.insert(document.positionAt(original.length),'\n// '+fact+'\n'+'// repeated ledger fixture comment\n'.repeat(500)));
  provider.actions.push(call('ledger_read','editor_read',{uri:document.uri.toString()}),request=>{
    assert(JSON.stringify(request).includes('You are Elpis Smart Prune'));assert(JSON.stringify(request).includes(fact));
    return message(JSON.stringify({items:[{call_id:'ledger_read',decision:'compact',content:fact}]}));
  },request=>{assert(JSON.stringify(request.input).includes(fact));return message('LEDGER_UNSAVED_FACT_431 retained.');});
  await frame.pointerClick('#prompt');await frame.locator('#prompt').fill('Read the current editor buffer and retain the delivery cutoff.');await page.keyboard.press('Enter');
  await eventually(async()=>await frame.evaluate('d.getElementById("send").getAttribute("aria-label")==="Send message"&&[...d.querySelectorAll("#ledger-pruning dd")][1]?.textContent==="1"'),'live compression reflected in ledger');
  await page.screenshot({path:path.join(data,'context-ledger-pruned.png')});
  const theme=vscode.workspace.getConfiguration('workbench').get('colorTheme');
  await vscode.workspace.getConfiguration('workbench').update('colorTheme','Default Dark Modern',vscode.ConfigurationTarget.Global);
  await eventually(async()=>await frame.evaluate('d.body.classList.contains("vscode-dark")'),'dark ledger theme');
  await page.screenshot({path:path.join(data,'context-ledger-dark.png')});
  await vscode.workspace.getConfiguration('workbench').update('colorTheme',theme,vscode.ConfigurationTarget.Global);
  await editor.edit(edit=>edit.replace(new vscode.Range(document.positionAt(0),document.positionAt(document.getText().length)),original));
  const afterCompression=provider.requests.length;
  await frame.locator('#smart-pruning-toggle').click();
  await eventually(async()=>(await frame.locator('#smart-pruning-state').textContent())==='Smart Pruning: off','disable confirmed by runtime');
  assert.equal(provider.requests.length,afterCompression,'disabling must not invoke optimizer');
  const goal='LEDGER_GOAL_SENTINEL: preserve editor changes and report evidence';
  await frame.locator('#context-ledger details:last-of-type > summary').click();
  await frame.locator('#goal-objective').fill(goal);await frame.locator('#goal-save').click();
  await eventually(async()=>(await frame.locator('#ledger-goal').textContent()).includes(goal),'real runtime goal set');
  await frame.locator('#ledger-close').click();await frame.locator('#ledger-open').click();
  await eventually(async()=>(await frame.locator('#ledger-goal').textContent()).includes(goal),'goal reload from runtime');
  await page.screenshot({path:path.join(data,'context-ledger.png')});
  await frame.locator('#goal-clear').click();
  await eventually(async()=>(await frame.locator('#ledger-goal').textContent())==='No active goal.','real goal clear');
  await frame.locator('#ledger-close').click();
  evidence.results.push({name:'Context Ledger: runtime Smart Pruning enable/disable do not rewrite history; goal set/read/clear round trip',passed:true});
};

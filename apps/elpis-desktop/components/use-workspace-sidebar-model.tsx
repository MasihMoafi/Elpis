"use client";

import { createSidebarThreadRow } from "@/components/sidebar-thread-row";
import { createSidebarBranches } from "@/components/sidebar-branches";
import { sidebarListKeys, useSidebarKeys } from "@/lib/use-workspace-navigation";
import { type Thread } from "@/lib/api";
import { createChatDeletion } from "@/lib/chat-deletion";
import { useChatReorder } from "@/lib/use-chat-reorder";
import { useSidebarThreads } from "@/lib/use-sidebar-threads";
import { createSidebarPlacement } from "@/lib/sidebar-placement";
import { useWorkspaceShortcuts } from "@/lib/use-workspace-shortcuts";
import { createSidebarChatSelection } from "@/lib/sidebar-chat-selection";
import { useWorkspaceOrder } from "@/lib/use-workspace-order";
import { createWorkspaceCommandMenu } from "@/lib/workspace-command-menu";
import { createSidebarAttention } from "@/lib/sidebar-attention";
import { createWorkspaceChatTabs } from "@/components/workspace-chat-tabs";
import type { WorkspaceActions } from "./use-workspace-actions";

export function useWorkspaceSidebarModel(previous: WorkspaceActions) {
  const {
    ready,
    connected,
    threads,
    hidden,
    selected,
    chatGroups,
    loveActivity,
    expanded,
    setExpanded,
    recordedWorkflow,
    loadChildren,
    search,
    attention,
    waitingIds,
    pins,
    projectChats,
    releaseChatOrder,
    searchInput,
    setError,
    setDeleteRunHistory,
    setDeleteTargets,
    hiddenPages,
    preferences,
    collapsedSections,
    collapsedProjects,
    checkedChildren,
    agentRunsOpen,
    shortcutAction,
    readOnlyRun,
    activeTurn,
    view,
    cwd,
    desktop,
    hasTerminal,
    side,
    sideChat,
    setSideChat,
    sidebar,
    sidebarCollapsed,
    tabs,
    commandReturnFocus,
    shortcutsReturnFocus,
    setCommandMenuOpen,
    setShortcutsOpen,
    setRenameRequest,
    setSettingsSection,
    newChat,
    stop,
    focusComposer,
    focusSearch,
    showSidebar,
    narrow,
    showPage,
    goHistory,
    loadThread,
    newChatTab,
    closeChatTab,
    cycleTabs,
    togglePinned,
    toggleBookmarked,
    selection,
    find,
    conversations,
    selectedRef,
    shownWhenDeleted,
    archiveThread,
    rowLinks,
    setDeletedNotice,
    noteKept,
    removeThreads,
    marked,
    setMarked,
    attentionState,
    options,
    projectState,
    children,
    updateGroups,
    foldsRef,
    changeFolds,
    assignProject,
    newProjectFrom,
    renameThread,
    searchTerm,
    runtime,
    bookmarks,
    childCursors,
    agentColours,
    setAgentRunsOpen,
    split,
    windowAvailable,
    openInTui,
    openSplit,
    openSessionWindow,
    markRead,
    prefetchThread,
    openInNewTab,
    clickRow,
    renameRequest,
    showTab,
    loadingChildren,
    session,
    dialogs,
    projectChanging,
    show,
    forward,
  } = previous;
  const sidebarModel = useSidebarThreads({
    ready,
    connected,
    threads,
    hidden,
    selected,
    chatGroups,
    loveActivity,
    expanded,
    setExpanded,
    recordedWorkflow,
    loadChildren,
    search,
    attention,
    waitingIds,
    pins,
    projectChats,
    releaseChatOrder,
    searchInput,
    setError,
    setDeleteRunHistory,
    setDeleteTargets,
    hiddenPages,
    preferences,
    collapsedSections,
    collapsedProjects,
    checkedChildren,
    agentRunsOpen,
  });
  const {
    workflowCatalog,
    workflowRoots,
    sidebarThreads,
    nativeParents,
    treeParents,
    sidebarState,
    needsYou,
    ordinaryThreads,
    ordinaryIds,
    pinnedChats,
    grouped,
    recentChats,
    ordered,
  } = sidebarModel;
  useWorkspaceShortcuts({
    shortcutAction,
    selected,
    ordered,
    readOnlyRun,
    activeTurn,
    view,
    cwd,
    desktop,
    hasTerminal,
    side,
    sideChat,
    setSideChat,
    sidebar,
    sidebarCollapsed,
    activeTabId: tabs.activeId,
    commandReturnFocus,
    shortcutsReturnFocus,
    setCommandMenuOpen,
    setShortcutsOpen,
    setRenameRequest,
    setSettingsSection,
    newChat,
    stop,
    focusComposer,
    focusSearch,
    undoDelete: () => undoDelete(),
    showSidebar: open => showSidebar(open),
    narrow: () => narrow(),
    show: showPage,
    goHistory,
    loadThread,
    archiveChats: chats => archiveChats(chats),
    chosenChats: () => chosenChats(),
    togglePin: thread => togglePin(thread),
    moveToEdge: (id, top) => moveToEdge(id, top),
    newChatTab,
    closeChatTab,
    cycleTabs,
  });
  const togglePin = (thread: Thread) => togglePinned(thread.id);
  const toggleBookmark = (thread: Thread) => toggleBookmarked(thread.id);
  const { chatsOf, chosenChats, withNested } = createSidebarChatSelection(sidebarModel, selection, selected, find);
  const { archiveChats, deleteChats, trashChats, undoDelete } = createChatDeletion({
    conversations,
    preferences,
    selectedRef,
    shownWhenDeleted,
    withNested,
    chatsOf,
    find,
    archiveThread,
    rowLinks,
    setDeleteRunHistory,
    setDeleteTargets,
    setDeletedNotice,
    setError,
    noteKept,
    removeThreads,
    loadThread,
  });
  const sidebarKeys = useSidebarKeys();
  const listKeys = (event: React.KeyboardEvent<HTMLDivElement>) =>
    sidebarListKeys(event, marked, () => setMarked([]), attentionFor, deleteChats, rowLinks);
  const attentionFor = createSidebarAttention(attentionState, options);
  const placement = createSidebarPlacement({
    model: sidebarModel,
    projectState,
    children,
    chatGroups,
    updateGroups,
    foldsRef,
    changeFolds,
    pins,
    marked,
    setMarked,
    setError,
    assignProject,
    newProjectFrom,
  });
  const { movingIds, canNest, placementReveal, revealPlacement, nestChats, organizationActions } = placement;
  async function renameDisplayedThread(thread: Thread, name: string, runId = workflowRoots.get(thread.id)?.id) {
    if (!runId) {
      await renameThread(thread, name);
      return;
    }
    const problem = workflowCatalog.rename(runId, name);
    if (problem) throw Error(problem);
  }
  const { chatReorder, moveToEdge } = useChatReorder({
    projectState,
    chatGroups,
    updateGroups,
    treeParents,
    pins,
    ordinaryThreads,
    ordinaryIds,
    pinnedChats,
    recentChats,
    grouped,
    movingIds,
    canNest,
    assignProject,
    nestChats,
    searchTerm,
    needsYou,
    sidebarState,
    setError,
  });
  const threadRow = createSidebarThreadRow({
    model: sidebarModel,
    runtime,
    loveActivity,
    attention,
    threads,
    selected,
    view,
    waitingIds,
    pins,
    bookmarks,
    marked,
    childCursors,
    searchTerm,
    agentColours,
    preferences,
    agentRunsOpen,
    setAgentRunsOpen,
    setExpanded,
    checkedChildren,
    setError,
    loadChildren,
    chatReorder,
    desktop,
    hasTerminal,
    pane: split.pane,
    windowAvailable,
    find,
    deleteChats,
    renameDisplayedThread,
    archiveChats,
    togglePin,
    toggleBookmark,
    openInTui,
    openSplit,
    openSessionWindow,
    organizationActions,
    attentionFor,
    chatsOf,
    movingIds,
    markRead,
    prefetchThread,
    openInNewTab,
    clickRow,
  });
  const { chatActions, chatTab } = createWorkspaceChatTabs({
    model: sidebarModel,
    placement,
    selected,
    view,
    tabs,
    marked,
    pins,
    bookmarks,
    renameRequest,
    pane: split.pane,
    hasTerminal,
    windowAvailable,
    find,
    chatsOf,
    attentionFor,
    deleteChats,
    renameDisplayedThread,
    archiveChats,
    togglePin,
    toggleBookmark,
    openInTui,
    openSplit,
    openSessionWindow,
    setRenameRequest,
    showTab,
    closeChatTab,
  });
  const { descendants, threadBranch, runDescendants, chatRows } = createSidebarBranches({
    model: sidebarModel,
    threadRow,
    chatReorder,
    chatGroups,
    updateGroups,
    hidden,
    expanded,
    childCursors,
    loadingChildren,
    searchTerm,
    loadChildren,
    find,
  });
  const { arrangedPages, pageReorder, projectReorder } = useWorkspaceOrder(
    preferences,
    hiddenPages,
    projectState,
    setError,
  );
  const commandActions = createWorkspaceCommandMenu({
    preferences,
    session,
    selection,
    dialogs,
    shortcutAction,
    pins,
    hiddenPages,
    desktop,
    hasTerminal,
    projectChanging,
    show,
  });
  forward.nativeParents = nativeParents;
  forward.archiveChats = archiveChats;
  forward.deleteChats = deleteChats;
  forward.placementReveal = placementReveal;
  forward.revealPlacement = revealPlacement;
  return {
    ...previous,
    sidebarModel,
    sidebarThreads,
    trashChats,
    undoDelete,
    sidebarKeys,
    listKeys,
    placement,
    chatReorder,
    threadRow,
    chatActions,
    chatTab,
    descendants,
    threadBranch,
    runDescendants,
    chatRows,
    arrangedPages,
    pageReorder,
    projectReorder,
    commandActions,
  };
}

export type WorkspaceSidebarModel = ReturnType<typeof useWorkspaceSidebarModel>;

"use client";

import { useWorkspaceChatActions } from "./use-workspace-chat-actions";
import { useWorkspaceCommands } from "./use-workspace-commands";

export function useWorkspaceActions(props: Parameters<typeof useWorkspaceChatActions>[0]) {
  const {
    forward,
    rememberModes,
    noteStartedMode,
    send,
    loadVersions,
    previous,
    openSessionWindow,
    projectActions,
    assignProject,
    selectProject,
    newProjectFrom,
    workIn,
    addProject,
    moveChat,
    moveChatToFolder,
    removeProject,
    continueHere,
    stop,
    deleteThread,
    renameThread,
    archiveThread,
    unarchived,
    conversationSettings,
    answerPlan,
    sendShell,
    replaceFrom,
    rewindFrom,
    switchRewind,
    approvalCardProps,
    earlier,
    openById,
    showPage,
    openInTui,
    openSettings,
    focusComposer,
    restoreComposerFocus,
    openComposerControl,
    closePanel,
    setDesktopPrompt,
    editQueued,
    chatConversation,
    chatFolder,
    personal,
    conversationCommands,
    startReview,
    sessionRows,
    slash,
    mention,
  } = useWorkspaceCommands(useWorkspaceChatActions(props));
  forward.rememberModes = rememberModes;
  forward.noteStartedMode = noteStartedMode;
  forward.send = send;
  forward.loadVersions = loadVersions;
  return {
    ...previous,
    openSessionWindow,
    projectActions,
    assignProject,
    selectProject,
    newProjectFrom,
    workIn,
    addProject,
    moveChat,
    moveChatToFolder,
    removeProject,
    continueHere,
    stop,
    deleteThread,
    renameThread,
    archiveThread,
    unarchived,
    conversationSettings,
    answerPlan,
    send,
    sendShell,
    replaceFrom,
    rewindFrom,
    switchRewind,
    approvalCardProps,
    earlier,
    openById,
    showPage,
    openInTui,
    openSettings,
    focusComposer,
    restoreComposerFocus,
    openComposerControl,
    closePanel,
    setDesktopPrompt,
    editQueued,
    chatConversation,
    chatFolder,
    personal,
    conversationCommands,
    startReview,
    sessionRows,
    slash,
    mention,
  };
}

export type WorkspaceActions = ReturnType<typeof useWorkspaceActions>;
